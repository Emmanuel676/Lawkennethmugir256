"""Write deploy/config.small.yaml: the same settings as config.yaml with a SMALLER built-in demonstration dataset.

    .\\.venv\\Scripts\\python.exe -m api.small_config            # 1,500 borrowers (default)
    .\\.venv\\Scripts\\python.exe -m api.small_config --borrowers 2000

For a host whose API runs out of memory (docs/DEPLOY_FREE.md). Use it by setting LENDING_MONITOR_CONFIG to
deploy/config.small.yaml for the build and the start command. Only two things differ from config.yaml:
generator.n_borrowers, and every data path, which moves under data/small/ so the full local demo (and its
fingerprint) is never overwritten. Every threshold and rule is the same; the numbers on screen are smaller, so they
no longer match the full demo's figures quoted in the docs.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

from src.config import PROJECT_ROOT, load_config

TARGET = PROJECT_ROOT / "deploy" / "config.small.yaml"
HEADER = ("# GENERATED by `python -m api.small_config` from config.yaml. Do not edit by hand: change config.yaml and\n"
          "# run the command again. Same settings, a smaller demonstration dataset (generator.n_borrowers), and data\n"
          "# paths under data/small/ so the full local demo is never overwritten. See docs/DEPLOY_FREE.md.\n")


def small_config(borrowers: int) -> dict:
    with open(PROJECT_ROOT / "config.yaml", encoding="utf-8") as handle:
        cfg = yaml.safe_load(handle)
    cfg["generator"]["n_borrowers"] = int(borrowers)
    for key, value in cfg["paths"].items():
        if isinstance(value, str) and value.startswith("data/"):
            cfg["paths"][key] = "data/small/" + value[len("data/"):]
    return cfg


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write deploy/config.small.yaml (a smaller demonstration dataset).")
    parser.add_argument("--borrowers", type=int, default=1500, help="borrowers in the hosted demo (default 1500)")
    args = parser.parse_args(argv)
    if not 500 <= args.borrowers <= 5000:
        print("Choose between 500 and 5,000 borrowers.")
        return 1
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(HEADER + yaml.safe_dump(small_config(args.borrowers), sort_keys=False, allow_unicode=True),
                      encoding="utf-8")
    load_config(TARGET)  # the generated file must pass the same checks as config.yaml
    print(f"Wrote {TARGET.relative_to(PROJECT_ROOT)} with {args.borrowers:,} borrowers.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
