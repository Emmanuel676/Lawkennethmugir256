class DatabaseUnavailable(RuntimeError):
    """The database cannot be reached. The message never contains the database URL."""


class AppDatabase:
    """SQLite: one connection per call, created lazily, with foreign keys on and one writer at a time."""

    kind = "sqlite"

    def __init__(self, path: Path):
        self.path = Path(path)
        self._ready = False
        self._lock = threading.RLock()

    def _init(self) -> None:
        if self._ready:
            return
        self.path.parent.mkdir(parents=True, exist_ok=True)
        conn = sqlite3.connect(str(self.path))
        try:
            conn.executescript(SCHEMA)
            conn.commit()
        finally:
            conn.close()
        self._ready = True

    @contextmanager
    def connect(self):
        """A connection inside one transaction (committed on success, rolled back on error)."""
        with self._lock:
            self._init()
            conn = sqlite3.connect(str(self.path), timeout=10)
            conn.row_factory = sqlite3.Row
            conn.execute("PRAGMA foreign_keys = ON")
            try:
                with conn:
                    yield conn
            finally:
                conn.close()


class _PgConnection:
    """Wraps a psycopg connection so the stores' '?' placeholders and row-by-name access work unchanged."""

    def __init__(self, conn):
        self._conn = conn

    def execute(self, sql: str, params=()):
        return self._conn.execute(sql.replace("?", "%s"), tuple(params))


class PostgresDatabase:
    """Postgres at a URL given only through the environment (DATABASE_URL). One connection per call.

    schema: an optional Postgres schema to use instead of 'public' (the tests use a fresh one per run).
    """

    kind = "postgres"

    def __init__(self, url: str, schema: str | None = None):
        if not url:
            raise ValueError("A database URL is needed.")
        self._url = url
        self._schema = schema
        self._ready = False
        self._lock = threading.RLock()

    def __repr__(self) -> str:  # never show the URL
        return f"PostgresDatabase(schema={self._schema!r})"

    def _raw(self):
        import psycopg
        from psycopg.rows import dict_row

        options = {"options": f"-c search_path={self._schema}"} if self._schema else {}
        try:
            return psycopg.connect(self._url, row_factory=dict_row, connect_timeout=15, **options)
        except psycopg.Error:
            # psycopg's own message can name the host or user; never pass it on.
            raise DatabaseUnavailable("The database set in DATABASE_URL cannot be reached. Check the setting and "
                                      "that the database is running.") from None

    def _init(self) -> None:
        if self._ready:
            return
        conn = self._raw()
        try:
            if self._schema:
                conn.execute(f'CREATE SCHEMA IF NOT EXISTS "{self._schema}"')
            for statement in PG_SCHEMA:
                conn.execute(statement)
            conn.commit()
        finally:
            conn.close()
        self._ready = True

    @contextmanager
    def connect(self):
        with self._lock:
            self._init()
            conn = self._raw()
            try:
                yield _PgConnection(conn)
                conn.commit()
            except BaseException:
                conn.rollback()
                raise
            finally:
                conn.close()


def open_database(settings):
    """The backend the settings ask for: Postgres when DATABASE_URL is set, otherwise SQLite in data_dir."""
    if settings.database_url:
        return PostgresDatabase(settings.database_url, schema=settings.database_schema)
    return AppDatabase(settings.data_dir / "app.db")
