"""The API's own database: users, sessions, dataset metadata, the audit log (Phase 12B), and in Postgres also the
imported datasets' files (Phase 13).

Two backends behind one small interface, `connect()`, a context manager that yields a connection with
`execute(sql, params)` and rows readable by column name:

  AppDatabase       SQLite, one file <data_dir>/app.db. Used when DATABASE_URL is not set (local use, unchanged).
  PostgresDatabase  Postgres at DATABASE_URL (for hosts with no permanent disk, for example Neon + Render).

The stores (api.accounts, api.store, api.audit) write SQL with '?' placeholders; the Postgres connection translates
them. Both create their tables on first use (never at import time, and never for read-only demo calls). Nothing here
stores a password or a session token in clear, and the database URL is never printed, logged or put in an error.
"""

from __future__ import annotations

import sqlite3
import threading
from contextlib import contextmanager
from pathlib import Path

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    email TEXT NOT NULL UNIQUE,
    role TEXT NOT NULL CHECK (role IN ('viewer', 'importer', 'admin')),
    password_hash TEXT NOT NULL,
    disabled INTEGER NOT NULL DEFAULT 0,
    created_at REAL NOT NULL,
    created_by TEXT NOT NULL,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until REAL NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at REAL NOT NULL,
    expires_at REAL NOT NULL
);
CREATE TABLE IF NOT EXISTS datasets (
    slug TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    source TEXT NOT NULL DEFAULT '',
    added_by TEXT NOT NULL,
    added_at REAL NOT NULL,
    updated_at REAL NOT NULL,
    as_of_date TEXT NOT NULL DEFAULT '',
    counts TEXT NOT NULL DEFAULT '{}',
    imports INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS audit (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    at REAL NOT NULL,
    actor TEXT NOT NULL,
    action TEXT NOT NULL,
    target TEXT NOT NULL DEFAULT '',
    detail TEXT NOT NULL DEFAULT ''
);
"""

# The same tables for Postgres (identity keys, double-precision times) plus the imported datasets' files as blobs.
